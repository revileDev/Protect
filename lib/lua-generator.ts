export function hexToRgb(hex: string): { r: number; g: number; b: number } {
  const clean = (hex || "#000000").replace("#", "");
  const num = parseInt(clean, 16);
  if (isNaN(num)) return { r: 0, g: 162, b: 255 };
  return {
    r: (num >> 16) & 255,
    g: (num >> 8) & 255,
    b: num & 255,
  };
}

